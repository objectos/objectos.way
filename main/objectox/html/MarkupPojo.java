package objectox.html;

import java.io.IOException;
import java.util.Collection;
import objectos.html.AttributeName;
import objectos.html.AttributeObject;
import objectos.html.ElementName;
import objectos.html.Markup;
import objectos.html.rec.AmbiguousInstruction;
import objectos.html.rec.AttributeInstruction;
import objectos.html.rec.ElementInstruction;
import objectos.html.rec.FlattenInstruction;
import objectos.html.rec.Fragment0;
import objectos.html.rec.Fragment1;
import objectos.html.rec.Fragment2;
import objectos.html.rec.Fragment3;
import objectos.html.rec.Fragment4;
import objectos.html.rec.FragmentInstruction;
import objectos.html.rec.Instruction;
import objectos.html.rec.NoOpInstruction;
import objectos.html.rec.RawInstruction;
import objectos.html.rec.TextInstruction;
import objectox.html.attr.AttributeNamePojo;
import objectox.html.rec.DocumentRecorder;

public sealed abstract class MarkupPojo
    extends MarkupGenerated
    implements Markup
    permits Markup.OfHtml {

  private final DocumentRecorder recorder;

  public MarkupPojo() {
    recorder = DocumentRecorder.create();
  }

  // ##################################################################
  // # BEGIN: Public API
  // ##################################################################

  @Override
  public final String toHtml() {
    throw new UnsupportedOperationException("Implement me");
  }

  /// Returns the HTML generated by this template suited to be used in JSON.
  ///
  /// @return the HTML generated by this template suited to be used in JSON
  public final String toJsonString() {
    throw new UnsupportedOperationException("Implement me");
  }

  @Override
  public final String toTestableText() {
    throw new UnsupportedOperationException("Implement me");
  }

  @Override
  public final String toString() {
    return toHtml();
  }

  @Override
  public final void writeTo(Appendable out) throws IOException {
    throw new UnsupportedOperationException("Implement me");
  }

  // ##################################################################
  // # END: Public API
  // ##################################################################

  // ##################################################################
  // # BEGIN: Way Support
  // ##################################################################

  @Override
  public final FragmentInstruction f(Fragment0 fragment) {
    return recorder.fragment(fragment);
  }

  @Override
  public final <T1> FragmentInstruction f(Fragment1<T1> fragment, T1 arg1) {
    return recorder.fragment(fragment, arg1);
  }

  @Override
  public final <T1, T2> FragmentInstruction f(Fragment2<T1, T2> fragment, T1 arg1, T2 arg2) {
    return recorder.fragment(fragment, arg1, arg2);
  }

  @Override
  public final <T1, T2, T3> FragmentInstruction f(Fragment3<T1, T2, T3> fragment, T1 arg1, T2 arg2, T3 arg3) {
    return recorder.fragment(fragment, arg1, arg2, arg3);
  }

  @Override
  public final <T1, T2, T3, T4> FragmentInstruction f(Fragment4<T1, T2, T3, T4> fragment, T1 arg1, T2 arg2, T3 arg3, T4 arg4) {
    return recorder.fragment(fragment, arg1, arg2, arg3, arg4);
  }

  @Override
  public final AttributeInstruction css(String value) {
    final StringBuilder sb;
    sb = new StringBuilder();

    final String formatted;
    formatted = AttributeNamePojo.formatAttrValue(value, sb);

    return attr0(AttributeNamePojo.CLASS, formatted);
  }

  @Override
  public final FlattenInstruction flatten(Instruction... contents) {
    return recorder.flatten(contents);
  }

  @Override
  public final FlattenInstruction flatten(Collection<? extends Instruction> contents) {
    final Instruction[] array;
    array = contents.toArray(Instruction[]::new);

    return recorder.flatten(array);
  }

  @Override
  public final NoOpInstruction noop() {
    return HtmlInstruction.NOOP;
  }

  // ##################################################################
  // # END: Way Support
  // ##################################################################

  // ##################################################################
  // # BEGIN: Elements
  // ##################################################################

  @Override
  public final void doctype() {
    recorder.doctype();
  }

  // ##################################################################
  // # END: Elements
  // ##################################################################

  // ##################################################################
  // # BEGIN: Attributes
  // ##################################################################

  @Override
  public final AttributeInstruction attr(AttributeObject object) {
    final AttributeName name;
    name = object.attrName();

    final String value;
    value = object.attrValue();

    if (value == null) {
      return attr0(name);
    } else {
      return attr0(name, value);
    }
  }

  // ##################################################################
  // # END: Attributes
  // ##################################################################

  // ##################################################################
  // # BEGIN: Text
  // ##################################################################

  @Override
  public final RawInstruction nbsp() {
    return recorder.raw("&nbsp;");
  }

  @Override
  public final RawInstruction raw(String text) {
    return recorder.raw(text);
  }

  @Override
  public final TextInstruction text(String text) {
    return recorder.text(text);
  }

  // ##################################################################
  // # END: Text
  // ##################################################################

  // ##################################################################
  // # BEGIN: Testable
  // ##################################################################

  @Override
  public final String testableCell(String value, int width) {
    return value;
  }

  @Override
  public final String testableField(String name, String value) {
    return value;
  }

  @Override
  public final String testableFieldName(String name) {
    return name;
  }

  @Override
  public final String testableFieldValue(String value) {
    return value;
  }

  @Override
  public final String testableH1(String value) {
    return value;
  }

  @Override
  public final String testableH2(String value) {
    return value;
  }

  @Override
  public final String testableH3(String value) {
    return value;
  }

  @Override
  public final String testableH4(String value) {
    return value;
  }

  @Override
  public final String testableH5(String value) {
    return value;
  }

  @Override
  public final String testableH6(String value) {
    return value;
  }

  @Override
  public final NoOpInstruction testableNewLine() {
    return HtmlInstruction.NOOP;
  }

  // ##################################################################
  // # END: Testable
  // ##################################################################

  @Override
  final AmbiguousInstruction ambiguous(Ambiguous name, String value) {
    return recorder.ambiguous(name, value);
  }

  @Override
  final AttributeInstruction attr0(AttributeName name) {
    return recorder.attribute(name);
  }

  @Override
  final AttributeInstruction attr0(AttributeName name, Object value) {
    return recorder.attribute(name, value);
  }

  @Override
  final ElementInstruction elem0(ElementName name, Instruction... contents) {
    return recorder.element(name, contents);
  }

  @Override
  final ElementInstruction elem0(ElementName name, String text) {
    final Instruction t;
    t = recorder.text(text);

    return recorder.element(name, t);
  }

}